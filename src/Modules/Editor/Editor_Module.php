<?php
/**
 * Block editor sidebar: loads the built editor bundle and hands it its configuration.
 *
 * @package Rankavia
 */

declare( strict_types=1 );

namespace Bixisoft\Rankavia\Modules\Editor;

use Bixisoft\Rankavia\Vendor\Core\Container;
use Bixisoft\Rankavia\Vendor\Core\Contracts\Module;
use Bixisoft\Rankavia\Vendor\Core\Settings\Settings;
use Bixisoft\Rankavia\Templates\Contexts;
use Bixisoft\Rankavia\Templates\Variables;
use RuntimeException;

/**
 * Enqueues the per-page SEO sidebar for public post types that use the block editor.
 */
final class Editor_Module implements Module {

	public const HANDLE = 'rankavia-editor';

	/**
	 * Shared container.
	 *
	 * @var Container|null
	 */
	private ?Container $container = null;

	/**
	 * Module id.
	 *
	 * @return string
	 */
	public function id(): string {
		return 'editor';
	}

	/**
	 * Nothing to bind.
	 *
	 * @param Container $container Shared container.
	 * @return void
	 */
	public function register( Container $container ): void {
		$this->container = $container;
	}

	/**
	 * Add editor hooks.
	 *
	 * @param Container $container Shared container.
	 * @return void
	 */
	public function boot( Container $container ): void {
		$this->container = $container;
		add_action( 'enqueue_block_editor_assets', array( $this, 'enqueue' ) );
	}

	/**
	 * Load the sidebar bundle and its config in the block editor of an eligible post type.
	 *
	 * @return void
	 */
	public function enqueue(): void {
		$type = $this->current_post_type();
		if ( '' === $type || ! $this->is_eligible( $type ) ) {
			return;
		}

		$asset_file = $this->asset_file();
		if ( ! file_exists( $asset_file ) ) {
			return;
		}

		/**
		 * Generated by @wordpress/scripts.
		 *
		 * @var array{dependencies: string[], version: string} $asset
		 */
		$asset = require $asset_file;

		wp_enqueue_script(
			self::HANDLE,
			RANKAVIA_URL . 'build/editor/index.js',
			$asset['dependencies'],
			$asset['version'],
			true
		);
		wp_enqueue_style( 'wp-components' );
		if ( file_exists( RANKAVIA_PATH . 'build/editor/style-index.css' ) ) {
			wp_enqueue_style( self::HANDLE, RANKAVIA_URL . 'build/editor/style-index.css', array( 'wp-components' ), $asset['version'] );
		}

		wp_add_inline_script(
			self::HANDLE,
			'window.rankaviaEditor = ' . (string) wp_json_encode( $this->config( $type ) ) . ';',
			'before'
		);
	}

	/**
	 * The config object the sidebar reads as window.rankaviaEditor.
	 *
	 * @param string $type Post type being edited.
	 * @return array<string, mixed>
	 */
	public function config( string $type ): array {
		$settings  = $this->settings();
		$separator = (string) $settings->get( 'separator' );
		$context   = 'post_type:' . $type;

		$titles = $settings->get( 'title_templates' );
		$title  = is_array( $titles ) && isset( $titles[ $context ] ) ? trim( (string) $titles[ $context ] ) : '';
		if ( '' === $title ) {
			$title = Contexts::default_title( $context );
		}

		$descriptions = $settings->get( 'description_templates' );
		$description  = is_array( $descriptions ) && isset( $descriptions[ $context ] )
			? trim( (string) $descriptions[ $context ] )
			: Contexts::default_description( $context );

		return array(
			'version'           => RANKAVIA_VERSION,
			'siteName'          => (string) get_bloginfo( 'name' ),
			'homeUrl'           => home_url( '/' ),
			'separator'         => '' !== trim( $separator ) ? $separator : '–',
			'postType'          => $type,
			'templates'         => array(
				'title'       => $title,
				'description' => $description,
			),
			'templateVariables' => Variables::samples(),
			'scoreThresholds'   => array(
				'titleMin'       => 30,
				'titleMax'       => 60,
				'descriptionMin' => 70,
				'descriptionMax' => 160,
			),
		);
	}

	/**
	 * Post type of the screen being shown, or an empty string.
	 *
	 * @return string
	 */
	private function current_post_type(): string {
		$screen = get_current_screen();
		if ( ! is_object( $screen ) ) {
			return '';
		}
		return (string) $screen->post_type;
	}

	/**
	 * Whether the post type is public and edited with the block editor.
	 *
	 * @param string $type Post type.
	 * @return bool
	 */
	private function is_eligible( string $type ): bool {
		$object = get_post_type_object( $type );
		if ( ! is_object( $object ) || empty( $object->public ) ) {
			return false;
		}
		return (bool) use_block_editor_for_post_type( $type );
	}

	/**
	 * Path of the asset manifest written by @wordpress/scripts for the editor entry.
	 *
	 * @return string
	 */
	private function asset_file(): string {
		/**
		 * Filters where the editor bundle's asset manifest is read from.
		 *
		 * @param string $path Absolute path to build/editor/index.asset.php.
		 */
		return (string) apply_filters( 'rankavia_editor_asset_file', RANKAVIA_PATH . 'build/editor/index.asset.php' );
	}

	/**
	 * Settings service.
	 *
	 * @return Settings
	 * @throws RuntimeException When the service is missing.
	 */
	private function settings(): Settings {
		$settings = null !== $this->container ? $this->container->get( 'settings' ) : null;
		if ( ! $settings instanceof Settings ) {
			throw new RuntimeException( 'The settings service is not registered.' );
		}
		return $settings;
	}
}
